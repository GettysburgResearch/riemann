"""Machine-generated tables for campaign C4 (reads the JSON outputs, writes tables_C4.md + manifest)."""
import os, sys, json, math, hashlib, glob, platform
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from detect_lib import kappa_cross

RES = "/home/user/riemann/research/exploratory/riemann-observatory/experiments/results/C4-weil-window-locality"
ZHU = {0.5: 1.05e-6, 0.6: 1.82e-9, 0.7: 4.99e-13, 0.8: 2.27e-17, 0.9: 5.91e-23, 1.0: 8.08e-30,
       1.1: 2.78e-38, 1.2: 9.98e-49}  # Zhu 2026 (arXiv:2608.24827) Table 3, certified upper bounds (even sector)


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    L = []
    w = L.append
    w("# C4 tables (machine-generated by make_tables.py; do not edit)\n")
    # profile
    p = os.path.join(RES, "lambda_profile_main.json")
    if os.path.exists(p):
        d = json.load(open(p))
        w("## T1. Window profile lambda_min(L): arithmetic side, Legendre basis, Arb assembly (non-rigorous quadrature)\n")
        w("| L | N | prec bits | lambda_even | lambda_odd | Zhu 2026 Table 3 (certified upper bd) | -ln lambda_even |")
        w("|---|---|---|---|---|---|---|")
        for r in d["rows"]:
            z = ZHU.get(round(r["L"], 3))
            le = float(r["lam_even"])
            w("| %.5g | %d | %d | %s | %s | %s | %.2f |" % (r["L"], r["N"], r["prec_bits"], r["lam_even"], r["lam_odd"],
              "%.3g" % z if z else "", -math.log(le)))
        w("")
    # detection
    kc = kappa_cross()
    for tag in ["lowT", "midT", "highT", "convN15", "convN_T100", "convN_T100_s3", "convN_T1000_s2", "convN_T1000_s3", "collision"]:
        p = os.path.join(RES, f"detect_{tag}.json")
        if not os.path.exists(p):
            continue
        d = json.load(open(p))
        w(f"## T2-{tag}. Detection thresholds L*(T0, delta) (model: {d['results'][0]['model']}, Nscale {d['results'][0]['Nscale']})\n")
        w("kappa = delta log(T0/2pi); kappa_c = %.4f (sinh k = 2k); L_N = (1/2)log(T0/2pi); L_flat solves sinh(2 delta L)/(2 delta) - L = L_N.\n" % kc)
        w("| T0 | delta | kappa | L_N | L_flat | L* | L* - min(L_N, L_flat) |")
        w("|---|---|---|---|---|---|---|")
        for r in d["results"]:
            for x in r["rows"]:
                Ls = x["L_star"]
                Lp = min(x["L_nyquist"], x["L_flat"])
                w("| %.2f | %.2f | %.3f | %.4f | %.4f | %s | %s |" % (r["T0"], x["delta"], x["kappa"], x["L_nyquist"], x["L_flat"],
                  "none<=%.2f" % x["bracket"][0] if Ls is None else "%.4f" % Ls, "" if Ls is None else "%+.4f" % (Ls - Lp)))
        w("")
    p = os.path.join(RES, "detect_ultra.json")
    if os.path.exists(p):
        d = json.load(open(p))
        w("## T3. Growth regime at very large heights (asymptotic archimedean symbol, exact prime phases)\n")
        w("| T0 | delta | kappa | L_N | L_flat | L* | L_sinh (Thm B test fn on true form) |")
        w("|---|---|---|---|---|---|---|")
        for x in d["rows"]:
            w("| %s | %.2f | %.2f | %.3f | %.4f | %s | %s |" % (x["T0"], x["delta"], x["kappa"], x["L_N"], x["L_flat"],
              "%.4f" % x["L_star"] if x["L_star"] else "none", "%.4f" % x["L_sinh"] if x["L_sinh"] else "none"))
        w("")
    p = os.path.join(RES, "thmB_table.json")
    if os.path.exists(p):
        d = json.load(open(p))
        w("## T4. Theorem C4-B (rigorous under H1): guaranteed detection window L_B vs Nyquist window L_N\n")
        w("| T | delta | L_N | L_flat | L_B | L_B/L_N |")
        w("|---|---|---|---|---|---|")
        for r in d["rows"]:
            w("| %s | %.2f | %.3f | %.3f | %s | %s |" % (r["T"], r["delta"], r["L_N"], r["L_flat"],
              "-" if r["L_B"] is None else "%.3f" % r["L_B"], "-" if r["L_B_over_L_N"] is None else "%.3f" % r["L_B_over_L_N"]))
        w("\nSmallest log10 T with L_B < L_N: " + json.dumps(d["log10T_crossover_LB_below_LN"]) + "\n")
    out = os.path.join(RES, "tables_C4.md")
    open(out, "w").write("\n".join(L) + "\n")
    man = {"python": platform.python_version(), "files": {}}
    try:
        import numpy, scipy, mpmath, flint
        man.update({"numpy": numpy.__version__, "scipy": scipy.__version__, "mpmath": mpmath.__version__, "python-flint": flint.__version__})
    except Exception:
        pass
    for f in sorted(glob.glob(os.path.join(RES, "*"))):
        if f.endswith("manifest_C4.json"):
            continue
        man["files"][os.path.basename(f)] = {"sha256": sha(f), "bytes": os.path.getsize(f)}
        try:
            mm = json.load(open(f)).get("meta", {}) if f.endswith(".json") else {}
            if isinstance(mm, dict) and "runtime_s" in mm:
                man["files"][os.path.basename(f)]["runtime_s"] = mm["runtime_s"]
        except Exception:
            pass
    json.dump(man, open(os.path.join(RES, "manifest_C4.json"), "w"), indent=1)
    print("wrote", out, sha(out))


if __name__ == "__main__":
    main()
