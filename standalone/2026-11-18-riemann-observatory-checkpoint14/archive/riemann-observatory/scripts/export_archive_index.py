#!/usr/bin/env python3
"""Build or query the read-only SQLite companion to the canonical JSONL archive."""

import argparse
from collections import Counter
from contextlib import closing
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import sqlite3
from tempfile import TemporaryDirectory
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
INDEX = "graphs/archive.sqlite"
DUMP = "graphs/archive.sql"
PAPER_ALIASES = "quality/paper_aliases.jsonl"
SOURCE_TABLES = {
    "corpus/bibliography.jsonl": "papers",
    "theorems/theorems.jsonl": "claims",
    "connections/connections.jsonl": "connections",
    "audits/findings.jsonl": "findings",
    "graphs/knowledge_graph.jsonl": None,
    "theorems/proof_dependencies.jsonl": "proof_dependencies",
}
RECORD_TABLES = (*[table for table in SOURCE_TABLES.values() if table], "graph_nodes", "graph_edges")
ID_PATTERN = re.compile(r"(?<![A-Za-z0-9_-])(?:PAPER|THM|LEM|OBS|CERT|COR|CONJ|DEF)-[A-Za-z0-9_-]+")
PAPER_ID = re.compile(r"PAPER-[A-Za-z0-9_-]+")
GENERATED = "<!-- Generated by scripts/export_archive_index.py. -->"

COMMON = """
    id TEXT PRIMARY KEY NOT NULL,
    canonical_file TEXT NOT NULL REFERENCES canonical_inputs(path),
    canonical_line INTEGER NOT NULL CHECK(canonical_line > 0),
    status TEXT,
    evidence TEXT NOT NULL CHECK(length(evidence) > 0),
    payload TEXT NOT NULL
"""
TABLE_COLUMNS = {
    "papers": """title TEXT NOT NULL, authors TEXT NOT NULL, family TEXT, year TEXT,
    audit_level INTEGER NOT NULL CHECK(audit_level BETWEEN 0 AND 3),
    whole_work_read INTEGER NOT NULL CHECK(whole_work_read IN (0,1)),
    selection_status TEXT NOT NULL, access_status TEXT NOT NULL, version TEXT, source_url TEXT NOT NULL,
    source_sha256 TEXT, record_path TEXT NOT NULL, track_file TEXT NOT NULL""",
    "claims": """paper_id TEXT REFERENCES papers(id), statement TEXT NOT NULL, kind TEXT,
    locator TEXT NOT NULL, track_file TEXT""",
    "connections": """statement TEXT NOT NULL, track_file TEXT NOT NULL""",
    "findings": """title TEXT NOT NULL, classification TEXT, track_file TEXT NOT NULL,
    claim_id TEXT REFERENCES claims(id),
    verified_author_error INTEGER NOT NULL CHECK(verified_author_error IN (0,1))""",
    "graph_nodes": "node_type TEXT NOT NULL, label TEXT NOT NULL",
    "graph_edges": """source_id TEXT NOT NULL REFERENCES graph_nodes(id),
    target_id TEXT NOT NULL REFERENCES graph_nodes(id), relation TEXT NOT NULL, original_id TEXT""",
    "proof_dependencies": """source_id TEXT NOT NULL REFERENCES graph_nodes(id),
    target_id TEXT NOT NULL REFERENCES graph_nodes(id), relation TEXT NOT NULL, original_id TEXT,
    locator TEXT NOT NULL, track_file TEXT""",
}
SCHEMA = """
CREATE TABLE canonical_inputs (
    path TEXT PRIMARY KEY NOT NULL,
    sha256 TEXT NOT NULL,
    row_count INTEGER NOT NULL CHECK(row_count >= 0)
);
""" + "\n".join(f"CREATE TABLE {table} ({COMMON}, {columns}, UNIQUE(canonical_file, canonical_line));" for table, columns in TABLE_COLUMNS.items()) + """
CREATE TABLE paper_claims (
    paper_id TEXT NOT NULL REFERENCES papers(id), claim_id TEXT NOT NULL REFERENCES claims(id),
    source_field TEXT NOT NULL, PRIMARY KEY(paper_id, claim_id, source_field)
);
CREATE TABLE paper_findings (
    paper_id TEXT NOT NULL REFERENCES papers(id), finding_id TEXT NOT NULL REFERENCES findings(id),
    source_field TEXT NOT NULL, PRIMARY KEY(paper_id, finding_id, source_field)
);
CREATE INDEX papers_title ON papers(title COLLATE NOCASE);
CREATE INDEX papers_family ON papers(family);
CREATE INDEX papers_scope ON papers(audit_level, access_status, whole_work_read);
CREATE INDEX claims_paper ON claims(paper_id);
CREATE INDEX claims_kind ON claims(kind);
CREATE INDEX findings_classification ON findings(classification, verified_author_error);
CREATE INDEX connections_status ON connections(status);
CREATE INDEX graph_nodes_type ON graph_nodes(node_type);
CREATE INDEX graph_edges_source ON graph_edges(source_id, relation);
CREATE INDEX graph_edges_target ON graph_edges(target_id, relation);
CREATE INDEX graph_edges_original ON graph_edges(original_id);
CREATE INDEX proof_dependencies_source ON proof_dependencies(source_id, relation);
CREATE INDEX proof_dependencies_target ON proof_dependencies(target_id, relation);
CREATE INDEX proof_dependencies_original ON proof_dependencies(original_id);
CREATE INDEX paper_claims_reverse ON paper_claims(claim_id);
CREATE INDEX paper_findings_reverse ON paper_findings(finding_id);
"""


def first(row, *fields):
    return next((row[field] for field in fields if row.get(field) not in (None, "", [], {})), None)


def display(value):
    """Retain list and object values as readable JSON in convenience fields."""
    if value is None or isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def assert_file(root, value):
    path = (root / value).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise ValueError(f"Missing or invalid local provenance path {value!r}")


def metadata(table, row, root):
    values = {"status": display(first(row, "status", "verification_status", "verification"))}
    if table == "papers":
        values.update(
            {field: row[field] for field in (
                "title", "audit_level", "whole_work_read", "selection_status",
                "source_url", "record_path", "track_file", "access_status",
            )}
        )
        values.update(
            status=row["access_status"], evidence=first(row, "scope_update_evidence", "record_path"),
            authors=display(row["authors"]), family=display(row.get("family")), year=display(row.get("year")),
            version=display(first(row, "canonical_version_expression", "version", "read_version", "source_edition")),
            source_sha256=row.get("source_sha256"),
        )
    elif table == "claims":
        values.update(
            paper_id=row.get("paper_id"), statement=row["statement"],
            kind=display(first(row, "claim_kind", "kind")), locator=display(row["locator"]),
            track_file=row.get("provenance_file"), evidence=first(row, "evidence", "locator"),
        )
    elif table == "connections":
        values.update(
            statement=display(first(row, "statement", "mathematically_explicit_connection", "proposed_claim", "claim",
                                    "connection", "new_claim_suggested", "kind")) or row["id"],
            track_file=row["provenance_file"],
            evidence=first(row, "evidence", "proof_reference", "provenance_file"),
        )
    elif table == "findings":
        values.update(
            title=display(first(row, "title", "statement")) or row["id"],
            classification=display(first(row, "classification", "category")), claim_id=row.get("claim_id"),
            track_file=row["track_file"], verified_author_error=bool(row.get("verified_author_error")),
            evidence=row["evidence"],
        )
    elif table == "graph_nodes":
        values.update(node_type=row["type"], label=display(row["label"]), evidence=row["evidence"])
    else:
        values.update(source_id=row["from"], target_id=row["to"], relation=row["relation"], original_id=row.get("id"),
                      evidence=first(row, "provenance", "locator"))
        if table == "proof_dependencies":
            values.update(locator=display(row["locator"]), track_file=row.get("track_file"))
    values["evidence"] = display(values["evidence"])
    for field in ("record_path", "track_file"):
        if values.get(field):
            assert_file(root, values[field])
    return values


def read_inputs(root):
    inputs = {}
    records = {table: [] for table in RECORD_TABLES}
    for path, table in SOURCE_TABLES.items():
        blob = (root / path).read_bytes()
        count = 0
        for line, payload in enumerate(blob.decode("utf-8").split("\n"), 1):
            if not payload.strip():
                continue
            # Preserve exact JSON text, excluding only the JSONL line terminator.
            payload = payload.removesuffix("\r")
            row = json.loads(payload)
            destination = table
            if destination is None:
                destination = {"node": "graph_nodes", "edge": "graph_edges"}[row["record_type"]]
            records[destination].append((path, line, payload, row))
            count += 1
        inputs[path] = (sha256(blob).hexdigest(), count)
    return inputs, records


def read_paper_aliases(root, inputs, papers):
    path = root / PAPER_ALIASES
    aliases = {}
    if not path.exists():
        return aliases
    blob = path.read_bytes()
    for line in blob.decode("utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        alias, target = row["alias"], row["canonical"]
        if not PAPER_ID.fullmatch(alias) or not PAPER_ID.fullmatch(target):
            raise ValueError(f"Invalid paper alias {alias!r} → {target!r}")
        if alias in papers or alias in aliases:
            raise ValueError(f"Conflicting paper alias {alias}")
        aliases[alias] = target
    inputs[PAPER_ALIASES] = (sha256(blob).hexdigest(), len(aliases))
    resolved = {}
    for alias, target in aliases.items():
        seen = {alias}
        while target in aliases:
            if target in seen:
                raise ValueError(f"Cyclic paper alias from {alias}")
            seen.add(target)
            target = aliases[target]
        if target not in papers:
            raise ValueError(f"Unknown canonical paper {target} for alias {alias}")
        resolved[alias] = target
    return resolved


def insert(connection, table, values):
    fields = ", ".join(values)
    placeholders = ", ".join("?" for _ in values)
    connection.execute(f"INSERT INTO {table} ({fields}) VALUES ({placeholders})", tuple(values.values()))


def edge_id(table, row, used_explicit, occurrences):
    explicit = row.get("id")
    if explicit and used_explicit[explicit] == 1:
        return explicit
    encoded = json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    base = f"{table}:{sha256(encoded).hexdigest()}"
    occurrences[base] += 1
    return base if occurrences[base] == 1 else f"{base}:{occurrences[base]}"


def record_ids(value):
    if isinstance(value, list):
        for item in value:
            yield from record_ids(item)
    elif isinstance(value, str):
        yield from ID_PATTERN.findall(value)


def add_paper_links(connection, records, aliases):
    papers = {row["id"] for _, _, _, row in records["papers"]}

    def referenced_papers(value):
        return {aliases.get(ident, ident) for ident in record_ids(value)} & papers

    claim_fields = ("paper_id", "paper_ids", "source_paper_id", "related_paper_id", "related_paper_ids")
    finding_fields = ("paper_id", "paper_ids", "sources")
    claim_papers = {}
    for _, _, _, row in records["claims"]:
        claim_papers[row["id"]] = set()
        for field in claim_fields:
            for paper in sorted(referenced_papers(row.get(field))):
                connection.execute("INSERT INTO paper_claims VALUES (?,?,?)", (paper, row["id"], field))
                claim_papers[row["id"]].add(paper)
    for _, _, _, row in records["findings"]:
        links = set()
        for field in finding_fields:
            links.update((paper, field) for paper in referenced_papers(row.get(field)))
        for field in ("claim_id", "sources"):
            for claim in set(record_ids(row.get(field))) & claim_papers.keys():
                links.update((paper, f"{field} → {claim}") for paper in claim_papers[claim])
        connection.executemany("INSERT INTO paper_findings VALUES (?,?,?)",
                               [(paper, row["id"], field) for paper, field in sorted(links)])


def validate(connection, root, inputs, records):
    missing = connection.execute("PRAGMA foreign_key_check").fetchall()
    if missing or connection.execute("PRAGMA integrity_check").fetchone() != ("ok",):
        raise ValueError(f"SQLite integrity check failed: {missing}")
    stored_inputs = {path: (digest, count) for path, digest, count in
                     connection.execute("SELECT path,sha256,row_count FROM canonical_inputs")}
    if stored_inputs != inputs:
        raise ValueError("Stored input counts or digests differ from canonical files")
    counts = {}
    for table, expected in records.items():
        indexed = list(connection.execute(f"""
            SELECT canonical_file, canonical_line, payload FROM {table}
            ORDER BY canonical_file, canonical_line
        """))
        counts[table] = len(indexed)
        original = [(path, number, payload) for path, number, payload, row in expected]
        if indexed != original:
            raise ValueError(f"{table}: indexed rows, line numbers, or exact payloads differ from canonical input")
    unmatched = connection.execute("""
        SELECT d.id FROM proof_dependencies d WHERE NOT EXISTS (
            SELECT 1 FROM graph_edges g WHERE g.source_id=d.source_id
            AND g.target_id=d.target_id AND g.relation=d.relation
        )
    """).fetchall()
    if unmatched:
        raise ValueError(f"Dependency edges missing from canonical graph: {unmatched}")
    for path, (digest, _) in inputs.items():
        if sha256((root / path).read_bytes()).hexdigest() != digest:
            raise ValueError(f"Canonical file changed during export: {path}")
    inconsistent = connection.execute("""
        SELECT id FROM papers WHERE whole_work_read <> (audit_level >= 1)
        OR (whole_work_read = 1 AND access_status <> 'full_text_accessed')
    """).fetchall()
    if inconsistent:
        raise ValueError(f"Paper audit or reading status inconsistent: {inconsistent}")
    for table in ("paper_claims", "paper_findings"):
        counts[table] = connection.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
    return counts


def md_text(value):
    return display(value).replace("\n", " ").replace("\r", " ").replace("<", "&lt;").replace(">", "&gt;")


def source_link(url):
    if urlsplit(url).scheme in {"http", "https"} and not any(c in url for c in "<>\r\n"):
        return f"<{url}>"
    return md_text(url)


def paper_view(row, claims, findings):
    lines = [GENERATED, "", f"# {row['id']} — {md_text(row['title'])}", ""]
    lines.extend((
        f"- Authors recorded in the bibliography — {md_text(', '.join(row['authors']) or 'Unspecified')}",
        f"- Source — {source_link(row['source_url'])}",
        f"- Selection — {md_text(row['selection_status'])}",
        f"- Access — {md_text(row['access_status'])}",
        f"- Whole work read — {'Yes' if row['whole_work_read'] else 'No'}",
        f"- Whole-work audit level — {row['audit_level']}",
        f"- Original record — [{row['record_path']}](../{row['record_path']})",
        f"- Original track — [{row['track_file']}](../{row['track_file']})",
    ))
    optional = (
        ("Recorded version", ("canonical_version_expression", "version", "read_version", "source_edition")),
        ("Source SHA-256", ("source_sha256",)),
        ("Reading scope", ("read_scope",)),
        ("Audit scope", ("audit_scope", "technical_audit_scope")),
        ("Source locator", ("source_locator", "statement_locator")),
        ("Scope evidence", ("scope_update_evidence", "audit_evidence")),
        ("Source record IDs", ("source_record_ids",)),
        ("Supplemental tracks", ("additional_scope_update_files",)),
    )
    for label, fields in optional:
        value = first(row, *fields)
        lines.append(f"- {label} — {md_text(value) if value is not None else 'Unspecified in this record'}")
    lines.extend(("", "## Linked claim records", ""))
    for ident, locator, track, fields in claims:
        lines.append(f"- `{ident}` · {md_text(fields)} · {md_text(locator)}"
                     + (f" · [{track}](../{track})" if track else ""))
    if not claims:
        lines.append("No explicit claim link was found in the indexed fields.")
    lines.extend(("", "## Linked finding records", ""))
    for ident, classification, track, fields in findings:
        label = f" · {md_text(classification)}" if classification else ""
        lines.append(f"- `{ident}`{label} · {md_text(fields)} · [{track}](../{track})")
    if not findings:
        lines.append("No explicit finding link was found in the indexed fields.")
    lines.extend(("", "Mathematical analysis beyond the cited, existing record scopes has not been assessed in this view.", ""))
    return "\n".join(lines)


def write_views(connection, destination, records, aliases, root):
    destination.mkdir()
    for _, _, _, row in records["papers"]:
        ident = row["id"]
        if not PAPER_ID.fullmatch(ident):
            raise ValueError(f"Unsafe paper view ID {ident!r}")
        claims = connection.execute("""
            SELECT c.id,c.locator,c.track_file,group_concat(pc.source_field, ', ')
            FROM paper_claims pc JOIN claims c ON c.id=pc.claim_id
            WHERE pc.paper_id=? GROUP BY c.id ORDER BY c.id
        """, (ident,)).fetchall()
        findings = connection.execute("""
            SELECT f.id,f.classification,f.track_file,group_concat(pf.source_field, ', ')
            FROM paper_findings pf JOIN findings f ON f.id=pf.finding_id
            WHERE pf.paper_id=? GROUP BY f.id ORDER BY f.id
        """, (ident,)).fetchall()
        (destination / f"{ident}.md").write_text(paper_view(row, claims, findings), encoding="utf-8")
    for alias, canonical in sorted(aliases.items()):
        lines = [GENERATED, "", f"# {alias} → {canonical}", "",
                 f"See the [canonical paper view for {canonical}]({canonical}.md)."]
        historical = f"papers/{alias}.md"
        if (root / historical).is_file():
            lines.append(f"The [historical source note](../{historical}) retains its original source and locators.")
        lines.extend(("", f"[Paper alias register](../{PAPER_ALIASES})", ""))
        (destination / f"{alias}.md").write_text("\n".join(lines), encoding="utf-8")


def build(root):
    inputs, records = read_inputs(root)
    aliases = read_paper_aliases(root, inputs, {row["id"] for _, _, _, row in records["papers"]})
    output = root / "paper_views"
    output.mkdir(exist_ok=True)
    with TemporaryDirectory(prefix=".index-build-", dir=root.parent) as temp:
        staging = Path(temp)
        with closing(sqlite3.connect(staging / "archive.sqlite")) as connection:
            connection.execute("PRAGMA foreign_keys = ON")
            connection.executescript(SCHEMA)
            connection.executemany("INSERT INTO canonical_inputs VALUES (?,?,?)",
                                   [(path, *metadata) for path, metadata in inputs.items()])
            for table in TABLE_COLUMNS:
                occurrences = Counter()
                explicit = Counter(row.get("id") for _, _, _, row in records[table])
                for path, number, payload, row in records[table]:
                    ident = edge_id(table, row, explicit, occurrences) if table in {
                        "graph_edges", "proof_dependencies",
                    } else row["id"]
                    insert(connection, table, dict(id=ident, canonical_file=path, canonical_line=number,
                                                   payload=payload, **metadata(table, row, root)))
            add_paper_links(connection, records, aliases)
            counts = validate(connection, root, inputs, records)
            connection.commit()
            with (staging / "archive.sql").open("w", encoding="utf-8", newline="\n") as dump:
                dump.write("\n".join(connection.iterdump()) + "\n")
            write_views(connection, staging / "views", records, aliases, root)
        moves = [(staging / "archive.sqlite", root / INDEX), (staging / "archive.sql", root / DUMP)]
        generated = {view.name: view for view in (staging / "views").iterdir()}
        stale = []
        for view in output.glob("PAPER-*.md"):
            owned = view.read_text(encoding="utf-8").startswith(GENERATED)
            if view.name in generated and not owned:
                raise ValueError(f"Refusing to overwrite a manually owned view: {view}")
            if view.name not in generated and owned:
                stale.append(view)
        moves.extend((view, output / name) for name, view in generated.items())
        for source, destination in moves:
            os.replace(source, destination)
        for view in stale:
            view.unlink()
    return {"validation": "PASS", "counts": counts, "paper_views": len(generated) - len(aliases),
            "alias_redirect_views": len(aliases)}


def connect_readonly(path):
    connection = sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True)
    connection.execute("PRAGMA query_only = ON")
    return connection


def search(connection, term, limit, exact):
    results = []
    pattern = term.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
    for table in RECORD_TABLES:
        edge = table in {"graph_edges", "proof_dependencies"}
        fields = ("id", "original_id", "source_id", "target_id") if edge else ("id",)
        operator = "= ?" if exact else "LIKE ? ESCAPE '\\'"
        test = " OR ".join(f"{field} {operator}" for field in fields)
        term_values = [term if exact else pattern] * len(fields)
        results.extend(
            dict(record_table=table, id=ident, canonical_file=path, canonical_line=line, payload=json.loads(payload))
            for ident, path, line, payload in connection.execute(
                f"SELECT id,canonical_file,canonical_line,payload FROM {table} WHERE {test} ORDER BY id LIMIT ?",
                (*term_values, limit),
            )
        )
    return results[:limit]


def query(connection, statement, limit):
    allowed = {sqlite3.SQLITE_SELECT, sqlite3.SQLITE_READ, sqlite3.SQLITE_FUNCTION, sqlite3.SQLITE_RECURSIVE}
    connection.set_authorizer(lambda action, *_: sqlite3.SQLITE_OK if action in allowed else sqlite3.SQLITE_DENY)
    connection.row_factory = sqlite3.Row
    cursor = connection.execute(statement)
    return [dict(row) for row in cursor.fetchmany(limit)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="Archive tree (defaults to the script's archive)")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", help="Rebuild and validate database, SQL dump and paper views")
    lookup = commands.add_parser("id", help="Find exact IDs or expand a literal prefix")
    lookup.add_argument("term")
    lookup.add_argument("--prefix", action="store_true")
    lookup.add_argument("--limit", type=int, default=25)
    sql = commands.add_parser("query", help="Run read-only SQL with JSON output")
    sql.add_argument("statement")
    sql.add_argument("--limit", type=int, default=100)
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if args.command == "build":
            result = build(root)
        else:
            if args.limit < 1:
                parser.error("--limit must be positive")
            with closing(connect_readonly(root / INDEX)) as connection:
                if args.command == "id":
                    result = search(connection, args.term, args.limit, exact=not args.prefix)
                else:
                    result = query(connection, args.statement, args.limit)
        print(json.dumps(result, ensure_ascii=False, indent=2))
    except (OSError, sqlite3.Error, ValueError, KeyError, TypeError) as exc:
        parser.exit(1, f"Archive index failed: {exc}\n")


if __name__ == "__main__":
    main()
