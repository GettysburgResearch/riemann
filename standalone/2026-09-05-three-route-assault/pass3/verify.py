def hashes(root=None):
    root=Path(root) if root is not None else Path(__file__).resolve().parent
    seen=set()
    for line in (root/'SHA256SUMS').read_text().splitlines():
        h,name=line.split('  ',1)
        if name not in MANIFEST_FILES or name in seen:raise ValueError('manifest path/duplicate')
        if len(h)!=64 or any(c not in '0123456789abcdef' for c in h):raise ValueError('manifest digest')
        if not (root/name).is_file():raise ValueError('manifest missing file')
        if hashlib.sha256((root/name).read_bytes()).hexdigest()!=h:raise ValueError('manifest mismatch: '+name)
        seen.add(name)
    if seen!=MANIFEST_FILES:raise ValueError('manifest coverage')

class Tests(unittest.TestCase):
    def test_float_rejected(self):
        with self.assertRaises(TypeError):Q(0.1)
    def test_bool_rejected(self):
        with self.assertRaises(TypeError):Q(True)
    def test_zero_division(self):
        with self.assertRaises(ZeroDivisionError):Q(1)/Q()
    def test_negative_degree(self):
        with self.assertRaises(ValueError):lag(-1)
    def test_degree_alias(self):
        with self.assertRaises(ValueError):lag(True)
    def test_singular_matrix(self):
        with self.assertRaises(ValueError):inv([[F(0)]])
    def test_noninteger_source_argument(self):
        with self.assertRaises(ValueError):sm.zeta_series(2.0)
    def test_tiny_prefactor_not_prerounded(self):
        out=sm.scale([sm.Ball(10**30)],F(1,10**60))[0]
        self.assertEqual(out.lo,F(1,10**30));self.assertEqual(out.hi,F(1,10**30))
    def test_changed_result(self):
        with self.assertRaises(ValueError):compare_text('{"ok":false}\n',{'ok':True})
    def test_boolean_integer_alias(self):
        with self.assertRaises(ValueError):compare_text(canonical({'ok':1}),{'ok':True})

    def test_manifest_coverage(self):
        import tempfile
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);(root/'SHA256SUMS').write_text('')
            with self.assertRaises(ValueError):hashes(root)
    def test_changed_proof_bytes(self):
        import tempfile
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            for name in MANIFEST_FILES:(root/name).write_text('fixture')
            digest=hashlib.sha256(b'fixture').hexdigest()
            (root/'SHA256SUMS').write_text(''.join(digest+'  '+name+'\n' for name in sorted(MANIFEST_FILES)))
            hashes(root)
            (root/'R1_MOMENTS.md').write_text('changed proof')
            with self.assertRaises(ValueError):hashes(root)

