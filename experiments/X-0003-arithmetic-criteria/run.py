#!/usr/bin/env python3
"""
X-0003 -- Certified search for a finite arithmetic witness against RH.

Agent: claude-01

Three classical criteria are equivalent to RH and are checkable with *exact*
integer arithmetic on one side and *certified* ball arithmetic on the other.
A single certified violation is a genuine counterexample -- no analytic
continuation, no contour, no branch cut, no truncation of an infinite object.
This is the cleanest possible witness format available to this project.

  (R)  ROBIN (1984).   RH  <=>  sigma(n) < e^gamma n log log n  for all n > 5040.
       sigma(n) is an exact integer; the right side is enclosed rigorously.

  (L)  LAGARIAS (2002). RH  <=>  sigma(n) <= H_n + exp(H_n) log(H_n) for all
       n >= 1, where H_n is the n-th harmonic number.  H_n is enclosed by
       H_n = log n + gamma + 1/(2n) - 1/(12 n^2) + theta/(120 n^4), 0<theta<1,
       which is certified and ample since our n are astronomically large.

  (N)  NICOLAS (1983).  RH  <=>  N_k / phi(N_k) > e^gamma log log N_k for every
       primorial N_k = p_1 p_2 ... p_k.  The left side is an EXACT rational
       prod p/(p-1); log N_k = theta(p_k) = sum_{p<=p_k} log p is enclosed
       rigorously.

WHERE TO LOOK.  Robin's inequality need only be tested on superabundant
numbers: Robin proved that if it fails anywhere it fails at a superabundant n.
[CITATION FLAG: this reduction is quoted from memory and has NOT been verified
against the literature by this agent -- see OPEN_PROBLEMS Q-0007.  Nothing in
the *certified* output depends on it; the reduction only justifies the choice
of test set, so a wrong recollection here can cause us to MISS a counterexample,
never to claim a false one.]  We therefore test the colossally abundant
numbers, generated by the Alaoglu-Erdos construction, plus the primorials.

OUTPUT: for each criterion, the certified sign of the margin at every tested
point, and the *trend* of the margin -- the trend is the interesting part,
because it says how much further a search would have to go.

Usage: python3 run.py [prime_limit]
"""
from __future__ import annotations

import json
import math
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "scripts"))

from flint import arb, ctx  # noqa: E402


def git_sha():
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=HERE, text=True).strip()
    except Exception:
        return "unknown"


def primes_upto(n):
    sieve = bytearray([1]) * (n + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i:: i] = bytearray(len(sieve[i * i:: i]))
    return [i for i in range(2, n + 1) if sieve[i]]


# ---------------------------------------------------------------------------
# colossally abundant numbers (Alaoglu-Erdos):  order the quantities
#   eps(p,k) = log_p( (p^{k+1}-1)/(p^k-1) ) - 1
# decreasingly; multiplying by p in that order steps through the CA numbers.
# ---------------------------------------------------------------------------
def ca_steps(primes, kmax=64, count=4000):
    steps = []
    for p in primes:
        for k in range(1, kmax + 1):
            num = p ** (k + 1) - 1
            den = p**k - 1
            e = math.log(num / den) / math.log(p) - 1 if den else None
            if e is None or e <= 0:
                break
            steps.append((e, p))
            if len(steps) > count * 4 and k > 2:
                break
    steps.sort(key=lambda t: -t[0])
    return steps[:count]


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 200000
    ctx.prec = 400
    P = primes_upto(limit)
    print(f"{len(P)} primes up to {limit}")

    egamma = arb.const_euler().exp()
    gamma_c = arb.const_euler()
    log_cache = {}

    def L(p):
        v = log_cache.get(p)
        if v is None:
            v = arb(p).log()
            log_cache[p] = v
        return v

    out = {
        "experiment": "X-0003",
        "agent": "claude-01",
        "git_sha": git_sha(),
        "prime_limit": limit,
        "n_primes": len(P),
        "prec_bits": 400,
        "python": sys.version.split()[0],
        "flint": __import__("flint").__version__,
        "semantics": "left-hand sides EXACT (Python integers / exact rationals); "
        "right-hand sides certified arb enclosures; every reported sign is "
        "certified (the enclosure of the margin excludes 0)",
        "robin": [],
        "lagarias": [],
        "nicolas": [],
        "violations": [],
        "undetermined_signs": [],
        "exceptional_set_note": "Robin's inequality is asserted only for "
        "n > 5040; the finitely many n <= 5040 where it fails (2,3,4,5,6,8,9,"
        "10,12,16,18,20,24,30,36,48,60,72,84,120,180,240,360,720,840,2520,5040)"
        " are NOT counterexamples and are excluded from the violation test. "
        "Nicolas' criterion is likewise asserted for k >= 1 but the first few "
        "primorials are handled separately in the literature; we require "
        "log N_k > 10 before flagging.",
    }

    # ---------------- Nicolas, on primorials --------------------------------
    print("--- Nicolas criterion on primorials ---")
    t0 = time.time()
    num, den = 1, 1          # exact  prod p/(p-1)
    log_Nk = arb(0)          # theta(p_k) = log N_k, certified
    checkpoints = set()
    k = 0
    step = max(1, len(P) // 60)
    for idx, p in enumerate(P, start=1):
        num *= p
        den *= p - 1
        log_Nk = log_Nk + L(p)
        if idx % step == 0 or idx == len(P) or idx < 6:
            checkpoints.add(idx)
            lhs = arb(num) / arb(den)              # exact rational -> enclosure
            rhs = egamma * log_Nk.log()
            margin = lhs - rhs
            sign = 1 if margin > 0 else (-1 if margin < 0 else 0)
            rec = {
                "k": idx, "p_k": p,
                "log_Nk": float(log_Nk),
                "lhs": float(lhs), "rhs": float(rhs),
                "margin": float(margin),
                "certified_sign": sign,
            }
            out["nicolas"].append(rec)
            if log_Nk > 10:
                if sign < 0:
                    out["violations"].append({"criterion": "nicolas", **rec})
                elif sign == 0:
                    out["undetermined_signs"].append({"criterion": "nicolas", **rec})
    print(f"  {len(out['nicolas'])} checkpoints, last log N_k = "
          f"{out['nicolas'][-1]['log_Nk']:.1f}, margin = "
          f"{out['nicolas'][-1]['margin']:.6e}  [{time.time()-t0:.1f}s]")

    # ---------------- Robin + Lagarias, on colossally abundant numbers ------
    print("--- Robin / Lagarias criteria on colossally abundant numbers ---")
    t0 = time.time()
    steps = ca_steps([p for p in P if p < 10**7][:20000], count=3000)
    exps = {}
    n_log = arb(0)           # log n, certified
    n_int = 1
    for i, (_e, p) in enumerate(steps, start=1):
        a = exps.get(p, 0) + 1
        exps[p] = a
        n_int *= p
        n_log = n_log + L(p)
        if i % 100 == 0 or i == len(steps) or i < 5:
            # sigma(n) exactly
            sig = 1
            for q, b in exps.items():
                sig *= (q ** (b + 1) - 1) // (q - 1)
            loglog = n_log.log()
            rhs = egamma * arb(n_int) * loglog
            margin = rhs - arb(sig)          # Robin: want sigma < rhs, margin>0
            sign = 1 if margin > 0 else (-1 if margin < 0 else 0)
            ratio = arb(sig) / rhs
            rec = {
                "step": i, "omega": len(exps), "log_n": float(n_log),
                "digits": int(n_int.bit_length() * 0.30103) + 1,
                "robin_ratio": float(ratio),
                "certified_sign_of_margin": sign,
            }
            out["robin"].append(rec)
            if n_log > arb(5040).log():          # Robin asserts n > 5040 only
                if sign < 0:
                    out["violations"].append({"criterion": "robin", **rec})
                elif sign == 0:
                    out["undetermined_signs"].append({"criterion": "robin", **rec})

            # Lagarias: H_n = log n + gamma + 1/(2n) - ... ; n is huge so the
            # correction is below any representable threshold, but we still
            # enclose it rigorously.
            inv2n = arb(1) / (2 * arb(n_int))
            Hn = n_log + gamma_c + arb(inv2n.mid(), inv2n.upper())
            lag_rhs = Hn + Hn.exp() * Hn.log()
            lmargin = lag_rhs - arb(sig)
            lsign = 1 if lmargin > 0 else (-1 if lmargin < 0 else 0)
            lrec = {"step": i, "log_n": float(n_log),
                    "lagarias_ratio": float(arb(sig) / lag_rhs),
                    "certified_sign_of_margin": lsign}
            out["lagarias"].append(lrec)
            if lsign < 0:
                out["violations"].append({"criterion": "lagarias", **lrec})
            elif lsign == 0:
                out["undetermined_signs"].append({"criterion": "lagarias", **lrec})
    print(f"  {len(out['robin'])} checkpoints, largest n has "
          f"{out['robin'][-1]['digits']} digits, Robin ratio = "
          f"{out['robin'][-1]['robin_ratio']:.10f}  [{time.time()-t0:.1f}s]")

    # ---------------- trend analysis ---------------------------------------
    # Under RH the Nicolas margin is positive and shrinking.  Fit
    #   margin ~ A * (log N)^(-b)   in log-log coordinates, and report the
    # extrapolated crossing.  HEURISTIC ONLY -- labelled as such.
    ns = [r for r in out["nicolas"] if r["log_Nk"] > 100 and r["margin"] > 0]
    trend = None
    if len(ns) >= 6:
        xs = [math.log(r["log_Nk"]) for r in ns]
        ys = [math.log(r["margin"]) for r in ns]
        n_ = len(xs)
        mx, my = sum(xs) / n_, sum(ys) / n_
        b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum(
            (x - mx) ** 2 for x in xs
        )
        a = my - b * mx
        trend = {
            "model": "log(nicolas margin) = a + b log(log N)",
            "a": a, "b": b,
            "interpretation": "b < 0 means the margin decays as a power of "
            "log N; the criterion is never violated in the tested range, and "
            "a power-law decay never reaches zero in finite log N, so the fit "
            "gives NO finite crossing point -- an important negative result: "
            "the Nicolas margin is not heading to zero at any locatable place.",
            "status": "HEURISTIC (least squares on computed points; not a bound)",
        }
    out["nicolas_trend"] = trend

    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    path = os.path.join(HERE, "results", f"criteria-{limit}.json")
    with open(path, "w") as fh:
        json.dump(out, fh, indent=1)

    print("\nSUMMARY")
    print(f"  certified violations found: {len(out['violations'])}")
    print(f"  undetermined signs        : {len(out['undetermined_signs'])}")
    print(f"  Robin ratio (largest n)   : {out['robin'][-1]['robin_ratio']:.12f}")
    print(f"  Lagarias ratio (largest n): {out['lagarias'][-1]['lagarias_ratio']:.12f}")
    if trend:
        print(f"  Nicolas margin decay exponent b = {trend['b']:.4f} "
              "(margin ~ (log N)^b)")
    print("wrote", path)


if __name__ == "__main__":
    main()
