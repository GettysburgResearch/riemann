int
main(int argc, char *argv[])
{
    slong prec = 192;
    int c, i, status, leading = 0;
    char ids[NCAND][NPOINTS][96];

    if (argc >= 2)
        prec = atol(argv[1]);
    if (prec < 128)
        return 2;
    flint_set_num_threads(2);

    flint_printf("{\n");
    flint_printf("  \"schema\":\"riemann.xi-passivity-value-balls.v1\",\n");
    flint_printf("  \"producer\":{\"backend\":\"FLINT C acb_dirichlet_zeta_jet_rs ambiguous-direction batch\",\"precision_bits\":%wd,\"threads\":2,\"discovery_boundary\":\"all vectors frozen from the prior 128-bit grid before this directed escalation\"},\n", prec);
    flint_printf("  \"points\":[\n");

    for (c = 0; c < NCAND; c++)
    {
        T_NUM = CANDIDATES[c].t_num;
        for (i = 0; i < NPOINTS; i++)
        {
            VECTOR[i] = CANDIDATES[c].vector[i];
            snprintf(ids[c][i], sizeof(ids[c][i]), "%s-x%d", CANDIDATES[c].id, X_BITS[i]);
            status = print_point(ids[c][i], X_BITS[i], prec, leading);
            if (status != 0)
                return status;
            leading = 1;
        }
    }

    flint_printf("\n  ],\n  \"channels\":[\n");
    for (c = 0; c < NCAND; c++)
    {
        if (c != 0)
            flint_printf(",\n");
        flint_printf("    {\"id\":\"%s-frozen-pick\",\"kind\":\"real-pick-rayleigh\",\"points\":[", CANDIDATES[c].id);
        for (i = 0; i < NPOINTS; i++)
        {
            if (i != 0)
                flint_printf(",");
            flint_printf("\"%s\"", ids[c][i]);
        }
        flint_printf("],\"vector\":[");
        for (i = 0; i < NPOINTS; i++)
        {
            if (i != 0)
                flint_printf(",");
            flint_printf("{\"numerator\":\"%s\",\"denominator\":\"1\"}", CANDIDATES[c].vector[i]);
        }
        flint_printf("]}");
    }

    flint_printf("\n  ],\n  \"declared_channel_ids\":[\n");
    for (c = 0; c < NCAND; c++)
    {
        if (c != 0)
            flint_printf(",\n");
        flint_printf("    \"%s-frozen-pick\"", CANDIDATES[c].id);
    }
    flint_printf("\n  ],\n");
    flint_printf("  \"classification\":\"precision escalation of every negative midpoint direction from the previous finite grid; exact checker decides signs\"\n");
    flint_printf("}\n");
    flint_cleanup();
    return 0;
}
