#!/usr/bin/env python3
"""Exact local obstruction to PR #243 L-23603's Bernstein/Hankel inference.

On the first open dyadic cell the reviewed spline is generated by

    f(t) = 8 exp(t) - 7 exp(t/2) - (3/2) t exp(t/2).

If k(x)=F_T''(x)=f''(T-x) were a Laplace transform of a positive measure,
then k*k''-(k')^2 would be nonnegative.  This verifier evaluates the
right-hand cell limit exactly with fractions.Fraction.
"""
from __future__ import annotations

from fractions import Fraction
import hashlib
import json


def derivative_at_zero(order: int) -> Fraction:
    """Return f^(order)(0) from the closed formula in L-23603.12."""
    if order < 0:
        raise ValueError("order must be nonnegative")
    return Fraction(8) - Fraction(7 + 3 * order, 2**order)


def as_json(value: Fraction) -> dict[str, int]:
    return {
        "numerator": value.numerator,
        "denominator": value.denominator,
    }


def main() -> int:
    f2 = derivative_at_zero(2)
    f3 = derivative_at_zero(3)
    f4 = derivative_at_zero(4)

    expected = (Fraction(19, 4), Fraction(6), Fraction(109, 16))
    if (f2, f3, f4) != expected:
        raise AssertionError("derivative normalization mismatch")

    # k=F_T'' and t=T-x, so k'=-f''' and k''=f''''.
    determinant = f2 * f4 - f3 * f3
    if determinant != Fraction(-233, 64):
        raise AssertionError("unexpected log-convexity determinant")
    if determinant >= 0:
        raise AssertionError("mutation failed to refute positive Bernstein measure")

    proof = {
        "schema": "riemann.x9516-hankel-logconvexity.v1",
        "verdict": "REFUTE_L23603_BERNSTEIN_HANKEL_INFERENCE",
        "f2_at_zero": as_json(f2),
        "f3_at_zero": as_json(f3),
        "f4_at_zero": as_json(f4),
        "log_convexity_determinant": as_json(determinant),
        "scope": (
            "Exact local obstruction to the claimed positive Bernstein/Hankel "
            "representation; does not disprove pointwise positivity of the "
            "carry profile or RH."
        ),
    }
    canonical = json.dumps(proof, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    expected_digest = "b51e3a48ca365119587af2896777ee59d5c875c049d0767487f3111163af4ce5"
    if digest != expected_digest:
        raise AssertionError("proof-object digest mismatch")

    output = dict(proof)
    output["proof_object_sha256"] = digest
    print(json.dumps(output, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
